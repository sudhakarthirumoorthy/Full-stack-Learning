# LIST
fruits = ["Apple", "Banana", "Mango"]
fruits.append("Orange")
print("List:", fruits)

# TUPLE
colors = ("Red", "Green", "Blue")
print("Tuple:", colors)

# SET
numbers = {1, 2, 2, 3, 4}
print("Set:", numbers)

# DICTIONARY
student = {
    "name": "Sudhakar",
    "age": 23,
    "course": "MCA"
}
print("Dictionary:", student)
print("Student name:", student["name"])