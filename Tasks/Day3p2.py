# concatination

first_name =" Sudhakar "
last_name =" T "
full_name = first_name + "." + last_name
print(full_name)

#repeation
print(full_name *5)

# indexing
print(full_name[3])
print(full_name[::-1])

#slicing
print(full_name[2:6])

#trasnformation
print(full_name.upper())
print(full_name.lower())
print(full_name.title())

# cleaning
print(full_name.strip())
print(full_name.lstrip())
print(full_name.rstrip())

# spliting
print(full_name.split())

